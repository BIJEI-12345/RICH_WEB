<?php
require_once __DIR__ . '/init_session.php';

error_reporting(E_ALL);
ini_set('display_errors', '0');
ini_set('log_errors', '1');

header('Content-Type: application/json');
header('Access-Control-Allow-Origin: *');
header('Access-Control-Allow-Methods: GET, OPTIONS');
header('Access-Control-Allow-Headers: Content-Type');

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(204);
    exit;
}

rich_session_start();

$isLoggedIn = ($_SESSION['logged_in'] ?? false) === true;
$hasUserId = !empty($_SESSION['user_id']);
$position = strtolower(trim((string) ($_SESSION['position'] ?? '')));

if (!$isLoggedIn || !$hasUserId) {
    http_response_code(403);
    echo json_encode(['success' => false, 'error' => 'Access denied. Please log in.']);
    exit;
}

if ($position !== 'admin') {
    http_response_code(403);
    echo json_encode(['success' => false, 'error' => 'Access denied. Audit trail is available to administrators only.']);
    exit;
}

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') !== 'GET') {
    http_response_code(405);
    header('Allow: GET, OPTIONS');
    echo json_encode(['success' => false, 'error' => 'Method not allowed']);
    exit;
}

require_once __DIR__ . '/config.php';

try {
    $connection = getPostgreSQLDatabaseConnection();
    $connection->exec(
        "CREATE TABLE IF NOT EXISTS audit_trail (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER DEFAULT NULL,
            user_email VARCHAR(255) NOT NULL,
            user_name VARCHAR(255) NOT NULL,
            user_position VARCHAR(255) DEFAULT NULL,
            action_type VARCHAR(100) NOT NULL,
            module VARCHAR(50) NOT NULL,
            description TEXT NOT NULL,
            details TEXT DEFAULT NULL,
            target_id INTEGER DEFAULT NULL,
            target_type VARCHAR(50) DEFAULT NULL,
            old_value TEXT DEFAULT NULL,
            new_value TEXT DEFAULT NULL,
            ip_address VARCHAR(45) DEFAULT NULL,
            user_agent TEXT DEFAULT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"
    );

    $scope = trim((string) ($_GET['scope'] ?? 'all'));
    $allowedScopes = [
        'login_history' => ['login', 'logout', 'login_failed'],
        'password' => ['password_changed'],
        'all' => ['login', 'logout', 'login_failed', 'password_changed'],
    ];
    $actions = $allowedScopes[$scope] ?? $allowedScopes['all'];
    $limit = filter_var($_GET['limit'] ?? 100, FILTER_VALIDATE_INT);
    $offset = filter_var($_GET['offset'] ?? 0, FILTER_VALIDATE_INT);
    $limit = $limit === false ? 100 : max(1, min($limit, 500));
    $offset = $offset === false ? 0 : max(0, $offset);
    $userEmail = trim((string) ($_GET['user_email'] ?? ''));

    $placeholders = implode(',', array_fill(0, count($actions), '?'));
    $conditions = ["at.module = 'auth'", "at.action_type IN ($placeholders)"];
    $params = $actions;

    if ($userEmail !== '') {
        $conditions[] = '(at.user_email ILIKE ? OR u.email ILIKE ?)';
        $emailPattern = '%' . $userEmail . '%';
        $params[] = $emailPattern;
        $params[] = $emailPattern;
    }

    $where = implode(' AND ', $conditions);
    $sql = "SELECT
                at.id,
                at.user_id,
                COALESCE(u.name, at.user_name) AS full_name,
                COALESCE(u.position, at.user_position) AS position,
                at.user_email AS email,
                at.action_type,
                at.module,
                at.description,
                at.created_at
            FROM audit_trail at
            LEFT JOIN brgy_users u ON at.user_id = u.id
            WHERE $where
            ORDER BY at.created_at DESC
            LIMIT ? OFFSET ?";
    $stmt = $connection->prepare($sql);
    $stmt->execute(array_merge($params, [$limit, $offset]));
    $auditTrail = $stmt->fetchAll(PDO::FETCH_ASSOC);

    $countSql = "SELECT COUNT(*)
                 FROM audit_trail at
                 LEFT JOIN brgy_users u ON at.user_id = u.id
                 WHERE $where";
    $countStmt = $connection->prepare($countSql);
    $countStmt->execute($params);
    $total = (int) $countStmt->fetchColumn();

    echo json_encode([
        'success' => true,
        'data' => $auditTrail,
        'total' => $total,
        'limit' => $limit,
        'offset' => $offset,
    ], JSON_UNESCAPED_UNICODE);
} catch (Throwable $e) {
    error_log('Error fetching audit trail: ' . $e->getMessage());
    http_response_code(500);
    echo json_encode(['success' => false, 'error' => 'Failed to fetch audit trail']);
}
